<h1>Sentimiento Muerto: Mi historia con la banda y su discografía</h1>

<p>Corría el año 1.999, creo que fue el año cuando adquirí mi primer CD de Sentimiento Muerto, creo que <em>fue Sin Sombra no hay Luz</em>. Luego, al poco tiempo, adquirí otro, luego otro, y así, conforme los iba encontrando en discotiendas en ese tiempo. Casi que sin darme cuenta los tenía todos, incluso <q>un album doble</q> se puede decir, donde graban casi que ensayando, y las mejores grabaciones quedaron registradas en <em>Aunque usted no lo quiera</em>, que obvio también lo adquirí apenas lo vi.</p>

