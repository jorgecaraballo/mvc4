<p>Tuve entonces la colección completa de Sentimiento Muerto en CD, menos <em>Fin del cuento</em>, pero ni importaba, pues todas las canciones de dicho album recopilatorio estaban repartidas en mi discografía de Sentimiento Muerto en CDs.</p>

<p>Sabiendo que la era de los CDs estaba por terminarse (y también para tener un respaldo), decidí pasar todas las canciones de los CDs originales a mp3 @320kbps. Luego, por MercadoLibre, subasté dichos CDs, que recuerdo que el ganador de la peleada subasta se los llevó todos por el equivalente a unos cincuenta dólares.</p>

