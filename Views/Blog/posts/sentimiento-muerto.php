<p>Igual quedé con mi preciada discografía completa de Sentimiento Muerto en mp3 @320kbps (que luego lamenté no haberlos pasado a FLAC (falta de conocimiento en ese momento)), pero igual, mp3 @320 kbps no es para nada mala calidad de sonido. Al contrario. En algunas aplicaciones, dicha tasa la califican como <q>insane</q> (refiriéndose a la buena calidad de sonido).</p>

<p>Decidí escribirles todo esto dado mi gusto y sentimiento por Sentimiento Muerto, que sé que muchos como yo comparten mis emociones y mi ya larga data de seguidor de dicha banda; como buen caraqueño que llegó a conocer también el Gran Café de Sabana Grande (<a href="https://twitter.com/abramartti/status/1747348921402249698" target="_blank" rel="noopener noreferrer">al parecer aún existe</a>), crecido entre los rockeros mayores de mi cuadra que mencionaban a <a href="https://es.wikipedia.org/wiki/Cayayo_Troconis" target="_blank">Cayayo</a>.</p>

